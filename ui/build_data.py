#!/usr/bin/env python3
"""Merge agent output + inbox into ui/data.js for the dashboard.

Reads   <root>/out/v1/ledger.json, <root>/out/v1/review_queue.json,
        <root>/out/v2/ledger.json, <root>/out/v2/review_queue.json,
        <root>/inbox.json
Writes  ui/data.js  (window.DATA = { v1: { records }, v2: { records } })

Rows in ledger.json become status "Logged", rows in review_queue.json become
"Needs review". Fields the agent didn't emit are written as null.

Usage:  python3 ui/build_data.py [--root DIR] [--inbox PATH] [--out PATH]
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Output field -> accepted input names (first non-null wins).
EMAIL_FIELDS = {
    "from": ["from", "sender", "from_address"],
    "subject": ["subject"],
    "received_at": ["received_at", "receivedAt", "date", "received"],
    "body": ["body", "text", "content"],
}
BILL_FIELDS = {
    "vendor": ["vendor", "vendor_name", "VendorRef"],
    "bill_number": ["bill_number", "invoice_number", "DocNumber", "invoiceNumber"],
    "bill_date": ["bill_date", "invoice_date", "TxnDate", "invoiceDate"],
    "due_date": ["due_date", "DueDate", "dueDate"],
    "terms": ["terms", "SalesTermRef"],
    "amount": ["amount", "total", "TotalAmt"],
    "currency": ["currency", "CurrencyRef"],
    "po": ["po", "po_number", "purchaseOrderNumber"],
    "flag_type": ["flag_type", "flag"],
    "reason": ["reason", "flag_reason"],
    "matched_email_id": ["matched_email_id", "duplicate_of"],
    "steps": ["steps", "trace"],
}
ID_KEYS = ["email_id", "source_email_id", "sourceEmailId", "emailId", "id"]
LIST_KEYS = ["records", "bills", "items", "emails", "entries"]
STATUS = {"ledger.json": "Logged", "review_queue.json": "Needs review"}


def load_list(path):
    """Return a list of dicts from a JSON file shaped as [..] or {"records": [..]}."""
    if not path.exists():
        print(f"warning: {path} not found, skipping", file=sys.stderr)
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(data, dict):
        data = next((data[k] for k in LIST_KEYS if isinstance(data.get(k), list)), [])
    return [row for row in data if isinstance(row, dict)]


def pick(row, names):
    for name in names:
        value = row.get(name)
        if isinstance(value, dict):  # QuickBooks refs: {"value": .., "name": ..}
            value = value.get("value") if name == "CurrencyRef" else value.get("name") or value.get("value")
        if value is not None:
            return value
    return None


def email_id(row):
    value = pick(row, ID_KEYS)
    return str(value) if value is not None else None


def build_version(out_dir, inbox):
    by_id = {}
    for filename, status in STATUS.items():  # review_queue last, so it wins
        for row in load_list(out_dir / filename):
            eid = email_id(row)
            if eid:
                by_id[eid] = (row, status)

    records = []
    for eid, (row, status) in by_id.items():
        email = inbox.get(eid, {})
        if not email:
            print(f"warning: {eid} not in inbox.json", file=sys.stderr)
        record = {"email_id": eid}
        record.update({k: pick(email, names) for k, names in EMAIL_FIELDS.items()})
        record.update({k: pick(row, names) for k, names in BILL_FIELDS.items()})
        record["status"] = status
        records.append(record)
    records.sort(key=lambda r: r["received_at"] or "")
    return {"records": records}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", type=Path, default=HERE.parent, help="folder containing out/ and inbox.json")
    ap.add_argument("--inbox", type=Path, help="path to inbox.json (default: <root>/inbox.json)")
    ap.add_argument("--out", type=Path, default=HERE / "data.js")
    args = ap.parse_args()

    inbox_path = args.inbox or args.root / "inbox.json"
    inbox = {email_id(e): e for e in load_list(inbox_path) if email_id(e)}
    data = {v: build_version(args.root / "out" / v, inbox) for v in ("v1", "v2")}

    js = json.dumps(data, indent=2, ensure_ascii=False).replace("</", "<\\/")
    args.out.write_text(
        "// Generated by build_data.py. Do not edit by hand.\nwindow.DATA = " + js + ";\n",
        encoding="utf-8",
    )
    counts = ", ".join(f"{v}: {len(data[v]['records'])} records" for v in data)
    print(f"wrote {args.out} ({counts})")


if __name__ == "__main__":
    main()
